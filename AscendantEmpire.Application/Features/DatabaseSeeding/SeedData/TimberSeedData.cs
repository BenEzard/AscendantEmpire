using AscendantEmpire.BackendContracts.MapResources.AddOrUpdateMapResourceType;
using AscendantEmpire.Domain.Enums.MapResources;
using AscendantEmpire.Domain.Enums.Maps;

namespace AscendantEmpire.Application.Features.DatabaseSeeding.SeedData;

/// <summary>
/// Timber: the wood standing on a Forest, Jungle or Woodland tile, held as a Distribution of the six log Assets.
/// </summary>
/// <remarks>
/// <para>
/// One type covers all three Biomes rather than one per Biome. A tile holds at most two MapResources, so six separate wood types could never sit on one, and
/// everything that is per-type - how it is extracted, how it is discovered, how long it lies dormant - is the same for every wood. What differs by Biome is
/// in the habitats, and what differs by tile is in the scenarios.
/// </para>
/// <para>
/// The scenarios are generated by <see cref="MapResourceDistributionScenarioGenerator"/> from the tables below. Two sets, because bamboo grows only in
/// jungle and the other woods only outside it, and a scenario's Biomes come from its band.
/// </para>
/// <para>
/// See <c>docs/design/campaign-map/map-resources.md</c>.
/// </para>
/// </remarks>
internal sealed class TimberSeedData : IMapResourceTypeSeed
{
    /// <summary>
    /// The category Timber is listed under in the MapResource Type Manager, seeded by <see cref="MapResourceCategorySeedData"/>.
    /// </summary>
    private const string _WOOD_CATEGORY_CODE = "wood";

    #region Asset codes
    // The six log Assets a Timber tile can hold. These are the codes the Asset upsert derives from the group code and each Asset's DisplayName, so they have
    // to stay in step with AssetSeedData - MapResourceTypeSeedDataTests checks every one against the Asset seed rather than trusting this list.
    private const string _OAK_LOG = "ConstructionMaterials.Wood.Logs.OakLog";
    private const string _GENERIC_LOG = "ConstructionMaterials.Wood.Logs.GenericLog";
    private const string _CEDAR_LOG = "ConstructionMaterials.Wood.Logs.CedarLog";
    private const string _ASH_LOG = "ConstructionMaterials.Wood.Logs.AshLog";
    private const string _EBONY_LOG = "ConstructionMaterials.Wood.Logs.EbonyLog";
    private const string _BAMBOO = "ConstructionMaterials.Wood.Logs.Bamboo";
    #endregion

    #region Habitats
    /// <summary>
    /// Where Timber grows, and its values there: the ceiling on a tile's total wood, and the share of that total it puts on each Round.
    /// </summary>
    /// <remarks>
    /// One row per Biome, covering every Geography. A jungle holds the most wood and grows it fastest; a woodland is the thinnest of the three. A ceiling is
    /// also what decides which quantity bands its Biome can hold at all.
    /// </remarks>
    private static readonly SeededHabitat[] _HABITATS =
    [
        new SeededHabitat(BiomeType.Forest, MaximumQuantity: 20_000, GrowthPercentage: 0.03m),
        new SeededHabitat(BiomeType.Jungle, MaximumQuantity: 26_000, GrowthPercentage: 0.04m),
        new SeededHabitat(BiomeType.Woodland, MaximumQuantity: 9_000, GrowthPercentage: 0.02m)
    ];
    #endregion

    #region Archetypes
    /// <summary>
    /// The composition shapes a Forest or Woodland tile's wood can take. No bamboo: it only grows in jungle.
    /// </summary>
    /// <remarks>
    /// Shares are percentages of the tile's total and sum to 100. Most of a tile is generic wood with a sprinkling of something better; the archetypes
    /// holding a lot of one named wood are the rare ones, which is what the rarity weight says.
    /// </remarks>
    private static readonly CompositionArchetype[] _BAMBOO_FREE_ARCHETYPES =
    [
        new CompositionArchetype("Pure stand", Rarity: 30, [(_GENERIC_LOG, 100)]),
        new CompositionArchetype("Oak mixed", Rarity: 20, [(_GENERIC_LOG, 85), (_OAK_LOG, 13), (_CEDAR_LOG, 2)]),
        new CompositionArchetype("Cedar mixed", Rarity: 18, [(_GENERIC_LOG, 88), (_CEDAR_LOG, 10), (_ASH_LOG, 2)]),
        new CompositionArchetype("Ash mixed", Rarity: 18, [(_GENERIC_LOG, 86), (_ASH_LOG, 12), (_OAK_LOG, 2)]),
        new CompositionArchetype("Broad mix", Rarity: 12, [(_GENERIC_LOG, 70), (_OAK_LOG, 12), (_CEDAR_LOG, 9), (_ASH_LOG, 8), (_EBONY_LOG, 1)]),
        new CompositionArchetype("Oak rich", Rarity: 5, [(_GENERIC_LOG, 45), (_OAK_LOG, 50), (_ASH_LOG, 5)]),
        new CompositionArchetype("Cedar rich", Rarity: 5, [(_GENERIC_LOG, 50), (_CEDAR_LOG, 45), (_OAK_LOG, 5)]),
        new CompositionArchetype("Ash rich", Rarity: 4, [(_GENERIC_LOG, 48), (_ASH_LOG, 47), (_CEDAR_LOG, 5)]),
        new CompositionArchetype("Ebony seam", Rarity: 2, [(_GENERIC_LOG, 96), (_EBONY_LOG, 3), (_OAK_LOG, 1)]),
        new CompositionArchetype("Ebony stand", Rarity: 1, [(_GENERIC_LOG, 40), (_EBONY_LOG, 55), (_CEDAR_LOG, 5)])
    ];

    /// <summary>
    /// The composition shapes a Jungle tile's wood can take: mostly bamboo, with some generic wood, and rarely anything else.
    /// </summary>
    private static readonly CompositionArchetype[] _JUNGLE_ARCHETYPES =
    [
        new CompositionArchetype("Bamboo thicket", Rarity: 30, [(_BAMBOO, 100)]),
        new CompositionArchetype("Bamboo stand", Rarity: 22, [(_BAMBOO, 80), (_GENERIC_LOG, 20)]),
        new CompositionArchetype("Bamboo and scrub", Rarity: 18, [(_BAMBOO, 70), (_GENERIC_LOG, 25), (_ASH_LOG, 5)]),
        new CompositionArchetype("Bamboo with ebony", Rarity: 6, [(_BAMBOO, 65), (_GENERIC_LOG, 30), (_EBONY_LOG, 5)]),
        new CompositionArchetype("Jungle hardwood", Rarity: 2, [(_BAMBOO, 40), (_GENERIC_LOG, 40), (_EBONY_LOG, 15), (_ASH_LOG, 5)])
    ];
    #endregion

    #region Quantity bands
    /// <summary>
    /// How much wood in total a Forest or Woodland tile starts with, and how likely each size is in each of those Biomes.
    /// </summary>
    /// <remarks>
    /// A weight is relative within its own Biome, so Woodland leaning towards the sparse end makes a woodland read as thinner than a forest without changing
    /// what a forest looks like. The dense band is above Woodland's ceiling, so it is dropped there by the generator's ceiling rule rather than being left
    /// out by hand - which means raising that ceiling is all it would take to let a woodland grow thick.
    /// </remarks>
    private static readonly QuantityBand[] _BAMBOO_FREE_BANDS =
    [
        new QuantityBand("sparse", Total: 3_000, [(BiomeType.Forest, 1), (BiomeType.Woodland, 5)]),
        new QuantityBand("established", Total: 9_000, [(BiomeType.Forest, 2), (BiomeType.Woodland, 4)]),
        new QuantityBand("dense", Total: 16_000, [(BiomeType.Forest, 1), (BiomeType.Woodland, 1)])
    ];

    /// <summary>
    /// How much wood in total a Jungle tile starts with. Larger throughout than a forest, as a jungle's ceiling is.
    /// </summary>
    private static readonly QuantityBand[] _JUNGLE_BANDS =
    [
        new QuantityBand("sparse", Total: 6_000, [(BiomeType.Jungle, 1)]),
        new QuantityBand("established", Total: 14_000, [(BiomeType.Jungle, 2)]),
        new QuantityBand("dense", Total: 24_000, [(BiomeType.Jungle, 1)])
    ];

    /// <summary>
    /// The bamboo-free set first, then the jungle set, which is the order the scenarios are numbered in.
    /// </summary>
    private static readonly ScenarioSet[] _SCENARIO_SETS =
    [
        new ScenarioSet(_BAMBOO_FREE_ARCHETYPES, _BAMBOO_FREE_BANDS),
        new ScenarioSet(_JUNGLE_ARCHETYPES, _JUNGLE_BANDS)
    ];
    #endregion

    public string Code => "Timber";

    public IReadOnlyCollection<string> AssetCodes => [_OAK_LOG, _GENERIC_LOG, _CEDAR_LOG, _ASH_LOG, _EBONY_LOG, _BAMBOO];

    public int ItemCount => MapResourceDistributionScenarioGenerator.CountScenarios(_SCENARIO_SETS);

    public AddOrUpdateMapResourceTypeDto Build(IReadOnlyDictionary<string, int> assetIdsByCode)
    {
        return new AddOrUpdateMapResourceTypeDto
        {
            Code = Code,
            DisplayName = "Timber",
            MapResourceCategoryCode = _WOOD_CATEGORY_CODE,

            // No icon: a tile covered in trees is already said by its Biome.
            IconPath = null,

            // A Distribution has to be renewable, and never spreads.
            IsRenewable = true,
            IsStratified = false,
            IsDistribution = true,

            ExtractionMethod = ExtractionMethod.Fell,
            CaptureLikelihood = null,
            RequiresResearchToExtract = false,

            // Trees are seen the moment a unit reaches the tile, so discovery is certain and needs no mechanic to switch it on. What a Player cannot see
            // exactly is how much wood is there, which is what the fuzzy factor range is for.
            IsDiscoverableByDefault = true,
            DiscoveryLikelihood = 1.0m,
            EstimationFuzzyFactorMin = 0.05m,
            EstimationFuzzyFactorMax = 0.15m,

            // A tile felled bare lies dormant for five Rounds, with a one-in-five chance each Round of coming back.
            SurvivalRounds = 5,
            ReseedLikelihood = 0.2m,

            Habitats = [.. _HABITATS.Select(habitat => habitat.ToDto())],

            // A Distribution holds its Assets in its scenarios, so it has no yields and no layers.
            DistributionScenarios = [.. MapResourceDistributionScenarioGenerator.Generate(assetIdsByCode, _HABITATS, _SCENARIO_SETS)]
        };
    }
}
