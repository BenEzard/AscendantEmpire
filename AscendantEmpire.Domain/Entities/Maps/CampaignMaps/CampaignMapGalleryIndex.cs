using AscendantEmpire.Domain.Enums.Maps;

using System.ComponentModel.DataAnnotations;

namespace AscendantEmpire.Domain.Entities.Maps.CampaignMaps;

public class CampaignMapGalleryIndex
{
    public const int MAX_MAP_NAME_LENGTH = 100;
    public const int MAX_DESCRIPTION_LENGTH = 500;
    public const int MAX_PATH_LENGTH = 500;

    public int Id { get; set; }

    [MaxLength(MAX_MAP_NAME_LENGTH)]
    public required string MapName { get; set; }

    [MaxLength(MAX_DESCRIPTION_LENGTH)]
    public string Description { get; set; } = string.Empty;

    public int Width { get; set; }
    public int Height { get; set; }
    public MapCreationStatus CreationStatus { get; set; }

    /// <summary>
    /// Generation progress as a percentage (0–100), updated by the background processing pipeline while the map is being created.
    /// </summary>
    /// <remarks>
    /// Drives the progress dialog the UI shows after queueing a new map.
    /// </remarks>
    public byte ProgressPercent { get; set; }

    public MapCreationEngine CreationEngine { get; set; }
    public required string Status { get; set; }
    public string? ErrorMessage { get; set; }
    public required string PropertiesJson { get; set; }
    public int CampaignMapOffsetId { get; set; }

    /// <summary>
    /// Should the map wrap horizontally?
    /// </summary>
    /// <remarks>This is set by the map creator as a recommendation.
    /// When a game is created, the player who creates the game can override the recommendation.</remarks>
    public bool HorizontalWrap { get; set; }

    /// <summary>
    /// Should the map wrap vertically?
    /// </summary>
    /// <remarks>This is set by the map creator as a recommendation.
    /// When a game is created, the player who creates the game can override the recommendation.</remarks>
    public bool VerticalWrap { get; set; }

    /// <summary>
    /// Absolute path to the geography preview PNG generated alongside the map.
    /// </summary>
    /// <remarks>Null if the map was not generated by the Perlin noise engine, or if preview rendering failed.</remarks>
    [MaxLength(MAX_PATH_LENGTH)]
    public string? GeographyMapPath { get; set; }

    /// <summary>
    /// Absolute path to the biome preview PNG generated alongside the map.
    /// </summary>
    /// <remarks>Null if the map was not generated by the Perlin noise engine, or if preview rendering failed.</remarks>
    [MaxLength(MAX_PATH_LENGTH)]
    public string? BiomeMapPath { get; set; }
}
